const sleep = ms => new Promise(r => setTimeout(r, ms))
const t = (await (await fetch('http://127.0.0.1:9222/json/list')).json()).find(x => x.type === 'page' && x.url.includes('/video-player'))
const ws = new WebSocket(t.webSocketDebuggerUrl); await new Promise(r => ws.addEventListener('open', r))
let id = 0; const pending = new Map(); const events = []
ws.addEventListener('message', e => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id) } else if (m.method) events.push(m) })
const send = (m, p = {}) => new Promise(r => { const i = ++id; pending.set(i, r); ws.send(JSON.stringify({ id: i, method: m, params: p })) })
const click = g => send('Runtime.evaluate', { expression: `document.querySelector('a[href*="/api/proxy"][download]')?.click()`, userGesture: g })
await send('Page.enable'); await send('Runtime.enable')
await send('Page.navigate', { url: 'http://127.0.0.1:3000/video-player?url=' + encodeURIComponent('http://127.0.0.1:3000/test-dl.mp4') })
await sleep(4000)
await send('Runtime.evaluate', { expression: `document.querySelector('button[title="下载"]').click()`, userGesture: true }); await sleep(700)
const n = () => events.filter(e => e.method === 'Page.downloadWillBegin').length
let a = n(); await click(true); await sleep(1200); console.log('① userGesture 点击 → 下载 +', n() - a)
await sleep(3400)
a = n(); await click(true); await sleep(1500); console.log('③ 冷却过后再点 → 下载 +', n() - a, '(期望 1)')
ws.close()
