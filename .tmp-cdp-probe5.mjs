const sleep = ms => new Promise(r => setTimeout(r, ms))
const t = (await (await fetch('http://127.0.0.1:9222/json/list')).json()).find(x => x.type === 'page' && x.url.includes('/video-player'))
const ws = new WebSocket(t.webSocketDebuggerUrl)
await new Promise(r => ws.addEventListener('open', r))
let id = 0; const pending = new Map(); const events = []
ws.addEventListener('message', e => { const m = JSON.parse(e.data)
  if (m.id && pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id) } else if (m.method) events.push(m) })
const send = (m, p = {}) => new Promise(r => { const i = ++id; pending.set(i, r); ws.send(JSON.stringify({ id: i, method: m, params: p })) })
const ev = async e => { const r = await send('Runtime.evaluate', { expression: e, awaitPromise: true, returnByValue: true }); return r.result?.exceptionDetails ? 'ERR:' + r.result.exceptionDetails.exception?.description?.slice(0,80) : r.result?.result?.value }
await send('Page.enable'); await send('Runtime.enable')
await send('Page.navigate', { url: 'http://127.0.0.1:3000/video-player?url=' + encodeURIComponent('http://127.0.0.1:3000/test-dl.mp4') })
await sleep(4000)
const begins = () => events.filter(e => e.method === 'Page.downloadWillBegin').length
const clickIt = () => ev(`(()=>{const a=document.querySelector('a[href*="/api/proxy"][download]'); if(!a) return 'NO_ANCHOR'; a.click(); return 'ok'})()`)
const noteOf = p => ev(`(()=>{const d=[...document.querySelectorAll('div')].map(x=>x.textContent).find(x=>x&&x.indexOf(${JSON.stringify(p)})===0); return d?d.slice(0,44):''})()`)
await ev(`document.querySelector('button[title="下载"]').click()`); await sleep(700)
let n = begins(); console.log('① 第一次点:', await clickIt()); await sleep(1400)
console.log('   下载 +', begins() - n, '| 提示:', await noteOf('已交给浏览器下载'), '| 格子:', await ev(`document.querySelector('a[href*="/api/proxy"][download]').textContent.trim().replace(/\s+/g,' ')`))
n = begins(); console.log('② 立刻再点:', await clickIt()); await sleep(1400)
console.log('   下载 +', begins() - n, '(期望 0) | 提示:', await noteOf('刚刚已经开始'))
await sleep(3000)
n = begins(); console.log('③ 3 秒后再点:', await clickIt()); await sleep(1600)
console.log('   下载 +', begins() - n, '(期望 1)')
ws.close()
