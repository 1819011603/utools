const sleep = ms => new Promise(r => setTimeout(r, ms))
const t = (await (await fetch('http://127.0.0.1:9222/json/list')).json()).find(x => x.type === 'page' && x.url.includes('/video-player'))
const ws = new WebSocket(t.webSocketDebuggerUrl)
await new Promise(r => ws.addEventListener('open', r))
let id = 0; const pending = new Map(); const events = []
ws.addEventListener('message', e => { const m = JSON.parse(e.data)
  if (m.id && pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id) } else if (m.method) events.push(m) })
const send = (m, p = {}) => new Promise(r => { const i = ++id; pending.set(i, r); ws.send(JSON.stringify({ id: i, method: m, params: p })) })
const ev = async e => { const r = await send('Runtime.evaluate', { expression: e, awaitPromise: true, returnByValue: true }); return r.result?.exceptionDetails ? 'ERR ' + r.result.exceptionDetails.text : r.result?.result?.value }
await send('Page.enable'); await send('Network.enable'); await send('Runtime.enable')
await send('Page.navigate', { url: 'http://127.0.0.1:3000/video-player?url=' + encodeURIComponent('http://127.0.0.1:3000/test-dl.mp4') })
await sleep(4000)
await ev(`window.__log=[]; document.addEventListener('click', e => window.__log.push('click:'+e.target.tagName+'.'+String(e.target.className).slice(0,30)+' defaultPrevented='+e.defaultPrevented), true); 1`)
await ev(`document.querySelector('button[title="下载"]').click()`)
await sleep(700)
console.log('抽屉里有几个下载格:', await ev(`document.querySelectorAll('a[href*="/api/proxy"][download]').length`))
// 用 JS 直接点
await ev(`document.querySelector('a[href*="/api/proxy"][download]').click()`)
await sleep(1500)
console.log('JS click 后 /api/proxy 请求:', events.filter(e => e.method === 'Network.requestWillBeSent' && e.params.request.url.includes('/api/proxy')).length)
console.log('downloadWillBegin:', events.filter(e => e.method.includes('download')).map(e => e.method))
console.log('事件日志:', await ev(`JSON.stringify(window.__log)`))
console.log('格子文本:', await ev(`document.querySelector('a[href*="/api/proxy"][download]')?.innerText.replace(/\n/g,'|')`))
console.log('提示条:', await ev(`[...document.querySelectorAll('div')].map(d=>d.textContent).find(t=>t?.startsWith('已交给浏览器下载'))?.slice(0,50)`))
ws.close()
